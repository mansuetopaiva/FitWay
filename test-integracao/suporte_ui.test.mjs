import { test } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { abrir } from "./harness.mjs";
import { navegador } from "./navegador.mjs";
process.env.ADMIN_EMAILS = "dono@x.com";
const { sql, chamar } = await abrir();
const sha = (t) => createHash("sha256").update(t).digest("hex");
await sql`insert into usuarios (email, nome, senha) values ('dono@x.com', 'Dono', 'x')`;
await sql`insert into admin_2fa (email, segredo_cifrado, ativado_em) values ('dono@x.com', 'x', now())`; // admin com o 2º fator ativado (a sessão de admin só vale assim)
await sql`insert into sessoes (token, email, expira) values (${sha("d".repeat(64))}, 'dono@x.com', now() + interval '1 day')`;

test("aluno abre chamado de pagamento, vê o aviso de resposta, responde, encerra e abre outro sobre isso", async () => {
  const tk = (await chamar({ acao: "criar", nome: "Ana", email: "ana@x.com", senha: "123456" })).token;
  await sql`insert into pedidos (id, email, tipo, status, valor, codigo) values ('PEDAAA', 'ana@x.com', 'inicial', 'pronto', 999, 'FW-1')`;
  const n = await navegador(chamar, { hash: "#/perfil", token: tk });
  await n.espera(() => n.$("#supCard"));
  assert.ok(!n.$(".ponto"));
  n.clicar("#supCard");
  await n.espera(() => /Você ainda não abriu nenhum chamado/.test(n.texto()));
  n.clicar(".sup-abrir");
  await n.espera(() => n.$("#supForm"));
  n.$("#supForm .btn").click();
  assert.equal(n.$("#supErr").textContent, "Escolha o assunto.");
  n.$("[name=assunto][value=treino]").click(); n.$("[name=assunto][value=treino]").dispatchEvent(new n.w.Event("change"));
  assert.match(n.texto(), /pare o treino e procure atendimento médico/);
  n.$("[name=assunto][value=pagamento]").click(); n.$("[name=assunto][value=pagamento]").dispatchEvent(new n.w.Event("change"));
  assert.match(n.$("#supPedido").textContent, /FW-1 · Treino personalizado · R\$ 9,99 · pronto/);
  n.$("#supPedido").value = "PEDAAA";
  n.$("#supTexto").value = "Paguei duas vezes\n<img src=x onerror=alert(1)>";
  n.$("#supForm .btn").click();
  await n.espera(() => n.$(".sup-conversa"));
  assert.ok(!n.$(".sup-texto img"), "texto nunca vira HTML");
  assert.match(n.$(".sup-texto").textContent, /<img src=x onerror=alert\(1\)>/);
  const [c] = await sql`select id, pedido_id from chamados`;
  assert.equal(c.pedido_id, "PEDAAA");
  // admin responde
  await chamar({ acao: "admin", op: "suporte_responder", id: c.id, texto: "Vamos devolver um." }, "d".repeat(64));
  n.ir("#/perfil");
  await n.espera(() => n.$("[data-aba-perfil] .ponto") && n.$("#supCard .ponto"));
  n.ir("#/suporte");
  await n.espera(() => n.$(".sup-item .ponto"));
  n.clicar(".sup-item");
  await n.espera(() => /Vamos devolver um\./.test(n.texto()));
  await n.espera(() => !n.$("[data-aba-perfil] .ponto"));
  n.$("#supTexto").value = "Obrigada";
  n.$("#supResp .btn").click();
  await n.espera(() => /Obrigada/.test(n.texto()) && /Aguardando o suporte/.test(n.texto()));
  n.clicar("#supEncerrar");
  await n.espera(() => /Este chamado foi encerrado/.test(n.texto()));
  n.clicar("#supDeNovo");
  await n.espera(() => n.$("#supForm") && n.$("#supPedido"));
  assert.equal(n.$("[name=assunto]:checked").value, "pagamento");
  assert.equal(n.$("#supPedido").value, "PEDAAA");
  assert.deepEqual(n.erros.map(String), []);
});
