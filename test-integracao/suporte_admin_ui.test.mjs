import { test } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { abrir } from "./harness.mjs";
import { navegador } from "./navegador.mjs";
process.env.ADMIN_EMAILS = "dono@x.com";
const { sql, chamar } = await abrir();
const sha = (t) => createHash("sha256").update(t).digest("hex");
await sql`insert into usuarios (email, nome, senha) values ('dono@x.com', 'Dono', 'x')`;
const TD = "d".repeat(64);
await sql`insert into sessoes (token, email, expira) values (${sha(TD)}, 'dono@x.com', now() + interval '1 day')`;
const JPEG = "data:image/jpeg;base64,/9j/4AAQSkZJRgABAQAAAQABAAD";

test("admin: aba Suporte com contagem, conversa com contexto, responder, encerrar, reabrir, anexo; excluir conta em duas etapas", async () => {
  const tk = (await chamar({ acao: "criar", nome: "Ana <b>", email: "ana@x.com", senha: "123456" })).token;
  await sql`insert into pedidos (id, email, tipo, status, valor, codigo) values ('PEDAAA', 'ana@x.com', 'inicial', 'pronto', 999, 'FW-1')`;
  const id = (await chamar({ acao: "chamado_abrir", assunto: "pagamento", texto: "Linha 1 <script>alert(1)</script>\nlinha 2", pedido_id: "PEDAAA", anexo: JPEG }, tk)).corpo.id;
  const n = await navegador(chamar, { hash: "#/admin/suporte", token: TD });
  await n.espera(() => n.$(".adm-secoes .adm-conta") && n.$(`a[href="#/admin/chamado.${id}"]`));
  assert.equal(n.$(".adm-secoes .adm-conta").textContent, "1");
  assert.match(n.$(`a[href="#/admin/chamado.${id}"]`).textContent, /Ana <b>.*Pagamento · Linha 1 <script>alert\(1\)<\/script>.*esperando há 0 min/s);
  assert.ok(!n.w.document.querySelector("#admLista script, #admLista b b"), "nada vira HTML");
  n.clicar(`a[href="#/admin/chamado.${id}"]`);
  await n.espera(() => n.$(".sup-ctx"));
  assert.match(n.$(".sup-ctx").textContent, /ana@x\.com/);
  assert.ok(n.$('.sup-ctx a[href="#/admin/pedido.PEDAAA"]'));
  assert.ok(n.$('.sup-ctx a[href="#/admin/ana%40x.com"]'));
  assert.equal(n.$(".sup-texto").textContent, "Linha 1 <script>alert(1)</script>\nlinha 2");
  n.clicar("[data-ch-anexo]");
  await n.espera(() => n.$(".sup-img img"));
  assert.equal((await sql`select count(*)::int as n from admin_log where acao = 'suporte_anexo_ver'`)[0].n, 1);
  n.$("#chTexto").value = "Vou devolver.";
  n.$("#chResp [type=submit]").click();
  await n.espera(() => /Vou devolver\./.test(n.texto()) && /Respondido/.test(n.$("#admDetTit").textContent));
  n.clicar("[data-ch-encerrar]");
  await n.espera(() => n.$("[data-ch-reabrir]"));
  n.clicar("[data-ch-reabrir]");
  await n.espera(() => n.$("[data-ch-encerrar]") && /Aguardando resposta/.test(n.$("#admDetTit").textContent));
  // excluir conta
  n.ir("#/admin/ana%40x.com");
  await n.espera(() => n.$("[data-excluir]"));
  n.clicar("[data-excluir]");
  await n.espera(() => n.$("#admExcluir"));
  n.$("#admExEmail").value = "outra@x.com";
  n.$("#admExcluir [type=submit]").click();
  await new Promise((r) => setTimeout(r, 100));
  assert.equal((await sql`select count(*)::int as n from usuarios where email = 'ana@x.com'`)[0].n, 1);
  n.$("#admExEmail").value = "ANA@x.com";
  n.$("#admExcluir [type=submit]").click();
  await n.espera(() => /Conta excluída/.test(n.$("#toast").textContent));
  assert.equal((await sql`select count(*)::int as n from usuarios where email = 'ana@x.com'`)[0].n, 0);
  assert.equal((await sql`select count(*)::int as n from chamados`)[0].n, 0);
  assert.deepEqual(n.erros.map(String), []);
});
